'use strict';
// Rebuild the new-mode read-only projection without executing legacy gameplay.
const fs = require('node:fs'), path = require('node:path'), vm = require('node:vm');
const root = path.resolve(__dirname, '../..');
function object(file, marker) {
    const source = fs.readFileSync(path.join(root, file), 'utf8');
    const start = source.indexOf(marker) + marker.length, end = source.indexOf('\n};', start) + 2;
    return vm.runInNewContext('(' + source.slice(start, end) + ')');
}
const book = object('data.js', 'const monsterBookData = '), layout = object('main.js', 'window.TITLE_SCREEN_DATA = ');
const growth = require('../../experimental_word_growth');
const keys = [...new Set([...Object.keys(growth.tree), ...Object.values(growth.tree).flat().map(e => e.next)])];
const data = Object.fromEntries(keys.map(id => [id, { description: book[id]?.desc || book[growth.visualSkin(id)]?.desc || '',
    layout: layout[id] || layout[growth.visualSkin(id)] || null }]));
fs.writeFileSync(path.join(root, 'experimental_word_collection_data.js'),
    "// Generated by scripts/experimental/build_collection_data.js; legacy descriptions and title placements.\n" +
    "(function(root,data){if(typeof module==='object'&&module.exports)module.exports=data;else root.ExperimentalWordCollectionData=data;})(typeof globalThis!=='undefined'?globalThis:this," + JSON.stringify(data, null, 2) + ');\n');
console.log(JSON.stringify({ entries: keys.length, missingDescriptions: keys.filter(k => !data[k].description), missingLayouts: keys.filter(k => !data[k].layout) }));
